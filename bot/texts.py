def generate_response(moods: list[str]) -> str:
    selected = set(moods)
    parts: list[str] = []

    if {"sad", "anxious"} & selected:
        parts.append(random.choice(supportive_messages))

    if "tired" in selected:
        parts.append(random.choice(care_messages))

    if "playful" in selected:
        parts.append(random.choice(playful_messages))

    if "miss_you" in selected:
        parts.append(random.choice(miss_you_messages))

    if not parts:
        parts.append(random.choice(neutral_messages))

    if len(selected) > 1 and len(parts) == 1:
        parts.append("Спасибо, что честно отмечаешь всё сразу. Я рядом с любым твоим состоянием.")

    return "\n\n".join(parts)
